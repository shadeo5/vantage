// ---------------------------------------------------------------------------
// Vantage content pipeline — wire spots.image_url → public Storage URLs.
//
// Run AFTER the out/images/<city>/ folders are uploaded to the public `spots`
// bucket. Emits UPDATE statements you paste into the Supabase SQL editor. The
// URL is deterministic (bucket/city/id.webp), so this needs no secret. Only the
// new drafted spots get a URL; the 5 hand-authored ATL spots keep image_url null
// and fall back to their bundled illustration in the app (B3).
//
// Run:  npm run image-urls   →  vantage/supabase/image_urls.sql
// ---------------------------------------------------------------------------

import { readFileSync, writeFileSync, existsSync } from "fs";

const PROJECT = "yqulquuzhkiwbucpqdcm";
const BASE = `https://${PROJECT}.supabase.co/storage/v1/object/public/spots`;
const FILES = { nashville: "nashville.json", atlanta: "atlanta.json" }; // drafted (imaged) sets

const out = [
  "-- Wire spots.image_url → public Storage URLs. GENERATED by build-image-urls.mjs.",
  "-- Run in the Supabase SQL editor after uploading the images to the `spots` bucket.",
  "begin;",
];
let n = 0;
for (const [city, file] of Object.entries(FILES)) {
  const path = new URL(`./content/${file}`, import.meta.url);
  if (!existsSync(path)) { console.warn(`  ! missing content/${file}`); continue; }
  for (const s of JSON.parse(readFileSync(path, "utf8"))) {
    out.push(`update public.spots set image_url = '${BASE}/${city}/${s.id}.webp' where id = '${s.id}';`);
    n++;
  }
}
out.push("commit;");

writeFileSync(new URL("../vantage/supabase/image_urls.sql", import.meta.url), out.join("\n") + "\n");
console.log(`wrote vantage/supabase/image_urls.sql (${n} image_url updates)`);
