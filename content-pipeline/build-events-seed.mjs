// ---------------------------------------------------------------------------
// Vantage content pipeline — build the Postgres EVENTS seed.
//
// Sibling of build-seed.mjs (spots). Reads the committed content/<city>-events.json
// catalog(s) and emits vantage/supabase/events_seed.sql — upserts into public.events
// — that you paste into the Supabase SQL editor AFTER schema.sql (so the events table
// exists). Same dollar-quoting ($vtg$…$vtg$) + idempotent `on conflict do update`
// pattern as the spots seed, so re-running just updates rows in place.
//
// The event shape is wider than a spot: window_start/window_end come from the nested
// `window` object (kept as text to preserve the date-only vs datetime local semantics),
// and kit_angles is a nested map stored as jsonb.
//
// Run:  npm run seed:events
// ---------------------------------------------------------------------------

import { readFileSync, writeFileSync, existsSync } from "fs";

// Which content files hold each city's events (mirrors CITIES in build-seed.mjs).
const CITIES = {
  atlanta: { files: ["atlanta-events.json"] },
};

const dq = (s) => (s == null ? "null" : `$vtg$${String(s)}$vtg$`);
const arr = (a) => (a && a.length ? `array[${a.map(dq).join(", ")}]::text[]` : `'{}'::text[]`);
const jb = (o) => (o == null ? `'{}'::jsonb` : `$vtg$${JSON.stringify(o)}$vtg$::jsonb`);
const num = (n) => (n == null ? "null" : String(n));

const out = [
  "-- Vantage events seed — GENERATED by content-pipeline/build-events-seed.mjs.",
  "-- Run in Supabase → SQL Editor AFTER schema.sql (the events table must exist).",
  "-- Idempotent (safe to re-run) — upserts by id.",
  "begin;",
];

const seen = new Set();
for (const [key, city] of Object.entries(CITIES)) {
  out.push(`\n-- ${key} events ----------------------------------------------------`);
  let count = 0;
  for (const file of city.files) {
    const path = new URL(`./content/${file}`, import.meta.url);
    if (!existsSync(path)) { console.warn(`  ! missing content/${file} — skipped`); continue; }
    for (const e of JSON.parse(readFileSync(path, "utf8"))) {
      if (seen.has(e.id)) console.warn(`  ! duplicate event id "${e.id}" (${e.name}) — later one wins`);
      seen.add(e.id);
      out.push(
        `insert into public.events (id, city_id, name, event_type, genres, neighborhood, venue_spot_id, recurrence, window_start, window_end, window_confidence, admission, ticketing, magnitude, window_type, tagline, reason, why, look, kit_angles, getting, source, published) values (`,
        `  ${dq(e.id)}, ${dq(key)}, ${dq(e.name)}, ${dq(e.eventType)}, ${arr(e.genres)}, ${dq(e.neighborhood)}, ${dq(e.venueSpotId)}, ${dq(e.recurrence)}, ${dq(e.window?.start)}, ${dq(e.window?.end)}, ${dq(e.windowConfidence)}, ${dq(e.admission)}, ${dq(e.ticketing)}, ${dq(e.magnitude)}, ${dq(e.windowType)}, ${dq(e.tagline)}, ${dq(e.reason)}, ${dq(e.why)}, ${arr(e.look)}, ${jb(e.kitAngles)}, ${dq(e.getting)}, ${dq(e.source)}, true)`,
        `  on conflict (id) do update set city_id=excluded.city_id, name=excluded.name, event_type=excluded.event_type, ` +
        `genres=excluded.genres, neighborhood=excluded.neighborhood, venue_spot_id=excluded.venue_spot_id, ` +
        `recurrence=excluded.recurrence, window_start=excluded.window_start, window_end=excluded.window_end, ` +
        `window_confidence=excluded.window_confidence, admission=excluded.admission, ticketing=excluded.ticketing, ` +
        `magnitude=excluded.magnitude, window_type=excluded.window_type, tagline=excluded.tagline, reason=excluded.reason, ` +
        `why=excluded.why, look=excluded.look, kit_angles=excluded.kit_angles, getting=excluded.getting, ` +
        `source=excluded.source, published=excluded.published;`
      );
      count++;
    }
  }
  console.log(`  ${key}: ${count} events`);
}
out.push("\ncommit;");

const dest = new URL("../vantage/supabase/events_seed.sql", import.meta.url);
writeFileSync(dest, out.join("\n") + "\n");
console.log(`\nwrote vantage/supabase/events_seed.sql  (${seen.size} events)`);
